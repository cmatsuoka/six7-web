#!/usr/bin/env bash
#
# Fetch the engine and build the wasm glue.
#
# The engine is libslopsix. Its sources are taken from SLOPSIX_SOURCE and
# copied into SLOPSIX_DIR, where they are compiled. The source tree is never
# written to: it may be a checkout that belongs to somebody else.
#
# The source is the sibling checkout ../slopsix when there is one, and
# otherwise the pinned commit, fetched into vendor/libslopsix-src. Update
# SLOPSIX_COMMIT deliberately.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SLOPSIX_REPO="${SLOPSIX_REPO:-https://github.com/cmatsuoka/slopsix.git}"
SLOPSIX_COMMIT="${SLOPSIX_COMMIT:-88b5cbc9790eea2ebbac3d049c680d24d13c55df}"
# The checkout of the library that carries the newest API.
SLOPSIX_SIBLING="${SLOPSIX_SIBLING:-$ROOT/../slopsix}"
# The pristine sources the build is made from.
SLOPSIX_SOURCE="${SLOPSIX_SOURCE:-}"
# The sources the build actually compiles: a copy of the sources above.
SLOPSIX_DIR="${SLOPSIX_DIR:-$ROOT/vendor/libslopsix}"
EMCC="${EMCC:-emcc}"
# Runtime assertions are a development aid: they are off in normal builds.
SIX7_ASSERTIONS="${SIX7_ASSERTIONS:-0}"
OUT_DIR="$ROOT/build"

if ! command -v "$EMCC" >/dev/null 2>&1; then
    cat >&2 <<'EOF'
error: emcc not found.

Install Emscripten (emsdk) and put it on PATH, or set EMCC=/path/to/emcc:

  git clone https://github.com/emscripten-core/emsdk.git
  cd emsdk && ./emsdk install latest && ./emsdk activate latest
  source ./emsdk_env.sh
EOF
    exit 1
fi

# Where the pristine sources come from.
if [ -z "$SLOPSIX_SOURCE" ]; then
    if [ -f "$SLOPSIX_SIBLING/include/slopsix.h" ]; then
        SLOPSIX_SOURCE="$SLOPSIX_SIBLING"
    else
        SLOPSIX_SOURCE="$ROOT/vendor/libslopsix-src"
    fi
fi

if [ ! -f "$SLOPSIX_SOURCE/include/slopsix.h" ]; then
    # No local checkout: fetch the pinned commit.
    if [ ! -d "$SLOPSIX_SOURCE/.git" ]; then
        mkdir -p "$(dirname "$SLOPSIX_SOURCE")"
        git clone "$SLOPSIX_REPO" "$SLOPSIX_SOURCE"
    fi

    if ! git -C "$SLOPSIX_SOURCE" fetch --depth 1 origin "$SLOPSIX_COMMIT"; then
        cat >&2 <<EOF
error: the pinned engine commit could not be fetched.

  $SLOPSIX_COMMIT

The commit has to be in the upstream repository:

  git -C $SLOPSIX_SOURCE fetch origin $SLOPSIX_COMMIT

A local checkout of the library can be used instead:

  SLOPSIX_SOURCE=/path/to/slopsix npm run build:wasm
EOF
        exit 1
    fi
    # The checkout is forced, so a tree that has drifted from the pinned
    # commit cannot leak into the build.
    git -C "$SLOPSIX_SOURCE" checkout --force --detach "$SLOPSIX_COMMIT"
fi

if [ ! -d "$SLOPSIX_SOURCE/src" ]; then
    echo "error: the library sources are missing: $SLOPSIX_SOURCE" >&2
    exit 1
fi

# The build compiles a copy of the sources, so the checkout the sources
# come from stays untouched.
if [ -e "$SLOPSIX_DIR/.git" ]; then
    cat >&2 <<EOF
error: SLOPSIX_DIR ($SLOPSIX_DIR) is a git checkout.

SLOPSIX_DIR is the build copy, not the source. Point SLOPSIX_SOURCE at the
sources instead:

  SLOPSIX_SOURCE=$SLOPSIX_DIR npm run build:wasm
EOF
    exit 1
fi
rm -rf "$SLOPSIX_DIR"
mkdir -p "$SLOPSIX_DIR"
cp -R "$SLOPSIX_SOURCE/include" "$SLOPSIX_DIR/include"
cp -R "$SLOPSIX_SOURCE/src" "$SLOPSIX_DIR/src"
if [ -f "$SLOPSIX_SOURCE/LICENSE" ]; then
    cp "$SLOPSIX_SOURCE/LICENSE" "$SLOPSIX_DIR/LICENSE"
fi

mkdir -p "$OUT_DIR"

read_version() {
    awk -v key="$1" '$1 == "#define" && $2 == key { print $3; exit }' \
        "$SLOPSIX_DIR/include/slopsix.h"
}

VERSION_MAJOR="$(read_version SLOPSIX_VERSION_MAJOR)"
VERSION_MINOR="$(read_version SLOPSIX_VERSION_MINOR)"
VERSION_PATCH="$(read_version SLOPSIX_VERSION_PATCH)"

if [ -z "$VERSION_MAJOR" ] || [ -z "$VERSION_MINOR" ] || [ -z "$VERSION_PATCH" ]; then
    echo "error: could not read the library version from $SLOPSIX_DIR/include/slopsix.h" >&2
    exit 1
fi

cat > "$OUT_DIR/version.ts" <<EOF
// Generated by scripts/build-wasm.sh - do not edit.
export const SLOPSIX_VERSION = '${VERSION_MAJOR}.${VERSION_MINOR}.${VERSION_PATCH}';
EOF

# The floating point diagnostics keep the library integer-only. They are
# only used where the compiler knows them.
FLOAT_WARN=""
if "$EMCC" -Wfloat-conversion -Wdouble-promotion -Werror -E -x c /dev/null \
    >/dev/null 2>&1; then
    FLOAT_WARN="-Wfloat-conversion -Wdouble-promotion"
fi

# Only the glue is exported. The allocator stays on: the library calls
# calloc() for its context.
EXPORTED_FUNCTIONS='["_malloc","_free","_six7_version_number","_six7_create","_six7_destroy","_six7_reset","_six7_set_voice","_six7_get_voice","_six7_process","_six7_note_on","_six7_note_off","_six7_all_notes_off","_six7_set_ctrl_value","_six7_set_ctrl_range","_six7_set_ctrl_assign","_six7_set_sustain","_six7_set_lfo_mode","_six7_set_key_mode","_six7_set_unison_detune","_six7_set_peg_range","_six7_set_peg_velocity","_six7_set_peg_rate_scaling","_six7_set_master_volume","_six7_set_output_gain","_six7_set_digital_output_gain","_six7_set_master_tune","_six7_set_pitch_bend","_six7_set_pitch_bend_range","_six7_voice_dump_size","_six7_voice_count","_six7_context_engine"]'

# Build with DX7S personality enabled. The DX7 is the default engine;
# the host picks DX7 or DX7S at context creation.
DX7S_DEFS="-DSLOPSIX_DX7S -DSLOPSIX_DX7S_PERSONALITY"

# The personality's own translation units live under src/dx7s/. A pinned
# engine without them still builds the DX7 alone.
SLOPSIX_SRCS=("$SLOPSIX_DIR"/src/*.c)
if compgen -G "$SLOPSIX_DIR/src/dx7s/*.c" >/dev/null; then
    SLOPSIX_SRCS+=("$SLOPSIX_DIR"/src/dx7s/*.c)
else
    DX7S_DEFS=""
fi

# The environment is the worker only. With "node" in it, the Emscripten
# runtime imports "module" for its require shim, and a browser cannot
# resolve that: the whole worklet module would fail to evaluate. The Node
# smoke test instantiates the wasm binary directly instead of importing
# the glue.
# shellcheck disable=SC2086
"$EMCC" \
    "$ROOT/wasm/slopsix_wasm.c" \
    "${SLOPSIX_SRCS[@]}" \
    $DX7S_DEFS \
    -I"$SLOPSIX_DIR/include" \
    -I"$SLOPSIX_DIR/src" \
    -std=c99 -O2 \
    -Wall -Wextra -Werror \
    $FLOAT_WARN \
    --no-entry \
    -o "$OUT_DIR/slopsix.mjs" \
    -sMODULARIZE=1 \
    -sEXPORT_ES6=1 \
    -sEXPORT_NAME=createSlopsixModule \
    -sENVIRONMENT=worker \
    -sFILESYSTEM=0 \
    -sMALLOC=emmalloc \
    -sINITIAL_MEMORY=16777216 \
    -sSTACK_SIZE=131072 \
    -sASSERTIONS="$SIX7_ASSERTIONS" \
    -sEXPORTED_FUNCTIONS="$EXPORTED_FUNCTIONS" \
    -sEXPORTED_RUNTIME_METHODS=HEAPU8,HEAPU16,HEAP32

echo "built $OUT_DIR/slopsix.mjs and $OUT_DIR/slopsix.wasm (libslopsix ${VERSION_MAJOR}.${VERSION_MINOR}.${VERSION_PATCH})"
